from datetime import datetime, date
from typing import Optional, Dict, Any, List
from sqlalchemy import String, Integer, Float, DateTime, Date, ForeignKey, JSON, Text, Boolean
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.db.base import Base, TimestampMixin

class RacePrediction(Base, TimestampMixin):
    """
    Stores race time predictions generated by ML models (Random Forest, XGBoost)
    and sports science formulas (Riegel baseline, Jack Daniels VDOT).
    """
    __tablename__ = "race_predictions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True)
    prediction_date: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow)
    
    target_distance: Mapped[str] = mapped_column(String(50)) # 5K, 10K, Half, Marathon
    
    # Model predictions in seconds
    predicted_time_seconds: Mapped[float] = mapped_column(Float, nullable=False)
    lower_bound_seconds: Mapped[Optional[float]] = mapped_column(Float, nullable=True) # 90% confidence lower bound
    upper_bound_seconds: Mapped[Optional[float]] = mapped_column(Float, nullable=True) # 90% confidence upper bound
    
    # Model Metadata
    model_name: Mapped[str] = mapped_column(String(50)) # 'xgboost', 'random_forest', 'riegel_baseline', 'ensemble'
    model_version: Mapped[str] = mapped_column(String(20), default="1.0.0")
    confidence_score: Mapped[float] = mapped_column(Float, default=0.85) # 0 to 1
    
    # Evaluation against ground truth if later run
    actual_time_seconds: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    error_seconds: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    
    # Key driving features / feature importances
    feature_snapshot: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="predictions")


class TrainingPlan(Base, TimestampMixin):
    """
    Adaptive training plan generated for a runner with structured microcycles.
    """
    __tablename__ = "training_plans"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True)
    
    name: Mapped[str] = mapped_column(String(100), default="Adaptive 8-Week Plan")
    target_race_distance: Mapped[str] = mapped_column(String(50), default="5K")
    start_date: Mapped[date] = mapped_column(Date, nullable=False)
    end_date: Mapped[date] = mapped_column(Date, nullable=False)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    
    # Plan parameterization
    current_weekly_km: Mapped[float] = mapped_column(Float)
    peak_weekly_km: Mapped[float] = mapped_column(Float)
    adaptation_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    
    # Structured schedule entries
    # e.g., [{"date": "2026-11-06", "day": "Friday", "type": "Easy Run", "distance_km": 6.0, "target_pace": "5:30/km", "description": "..."}]
    schedule: Mapped[List[Dict[str, Any]]] = mapped_column(JSON, default=list)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="training_plans")
